import api from './api';

const list = (url) => (params) => api.get(url, { params }).then((r) => ({ items: r.data.data, pagination: r.data.pagination }));
const data = (r) => r.data.data;

export const dashboardApi = {
  admin: () => api.get('/dashboard/admin').then(data),
  librarian: () => api.get('/dashboard/librarian').then(data),
};

export const staffRequestsApi = {
  list: list('/requests'),
  approve: (id) => api.patch(`/requests/${id}/approve`).then(data),
  reject: (id, reason) => api.patch(`/requests/${id}/reject`, { reason: reason || undefined }).then(data),
};

export const staffRenewalsApi = {
  list: list('/renewals'),
  approve: (id) => api.patch(`/renewals/${id}/approve`).then(data),
  reject: (id, reason) => api.patch(`/renewals/${id}/reject`, { reason: reason || undefined }).then(data),
};

export const staffIssuesApi = {
  list: list('/issues'),
  issue: (studentId, bookId) => api.post('/issues', { studentId, bookId }).then(data),
  returnBook: (id) => api.patch(`/issues/${id}/return`).then(data),
};

export const membersApi = {
  list: list('/members'),
};

Object.assign(membersApi, {
  get: (id) => api.get(`/members/${id}`).then(data),
  create: (payload) => api.post('/members', payload).then(data),
  update: (id, payload) => api.patch(`/members/${id}`, payload).then(data),
  setStatus: (id, status) => api.patch(`/members/${id}/status`, { status }).then(data),
  setRole: (id, role) => api.patch(`/members/${id}/role`, { role }).then(data),
});

export const finesApi = {
  list: list('/fines'),
  pay: (id, payload) => api.post(`/fines/${id}/payments`, payload).then(data),
  waive: (id, reason) => api.patch(`/fines/${id}/waive`, { reason }).then(data),
};

export const reportsApi = {
  borrowing: (params) => api.get('/reports/borrowing', { params }).then(data),
  fines: (params) => api.get('/reports/fines', { params }).then(data),
  inventory: () => api.get('/reports/inventory').then(data),
};

// CSV is generated by the server from authorised data; the browser only saves it.
export async function downloadCsv(report, params, filename) {
  const res = await api.get(`/reports/${report}`, { params: { ...params, format: 'csv' }, responseType: 'blob' });
  const url = URL.createObjectURL(res.data);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
